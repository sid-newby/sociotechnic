import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readdirSync, realpathSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { setTimeout as sleep } from 'node:timers/promises';
import { createMemoryStore, setStore } from '../src/db/store.ts';
import { initializeAgentVersions } from '../src/agent-versions.ts';
import { readJob } from '../src/job-store.ts';
import { fakeRunner } from '../ui/runner.ts';
import { startServer } from '../ui/server.ts';

const { chromium } = await import(process.env.SOCIOTECHNIC_PLAYWRIGHT_MODULE ?? 'playwright');
const root = realpathSync(mkdtempSync(join(tmpdir(), 'sociotechnic-wizard-')));
const output = process.env.SOCIOTECHNIC_BROWSER_PROOF ?? mkdtempSync(join(tmpdir(), 'sociotechnic-wizard-proof-'));
mkdirSync(output, { recursive: true });
const home = join(root, 'user');
const projects = join(home, 'Prog');
mkdirSync(projects, { recursive: true });
mkdirSync(join(projects, 'existing'));
process.env.HOME = home;
process.env.SOCIOTECHNIC_HOME = join(root, 'engine');
process.env.SOCIOTECHNIC_DATABASE_URL = 'off';
process.env.GIT_CONFIG_GLOBAL = '/dev/null';
process.env.GIT_CONFIG_NOSYSTEM = '1';
process.env.GIT_AUTHOR_NAME = process.env.GIT_COMMITTER_NAME = 'Wizard test';
process.env.GIT_AUTHOR_EMAIL = process.env.GIT_COMMITTER_EMAIL = 'test@example.invalid';
const store = createMemoryStore();
setStore(store);
let server, browser;
try {
  await initializeAgentVersions(store, [], []);
  server = await startServer({ port: 0, runner: () => fakeRunner(join(dirname(fileURLToPath(import.meta.url)), '../tests/fixtures/fake-agent.mjs')) });
  browser = await chromium.launch({ channel: 'chrome', headless: true });
  let context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, colorScheme: 'dark', reducedMotion: 'reduce' });
  let page = await context.newPage();
  const errors = [];
  const observe = () => page.on('pageerror', error => errors.push(error.message));
  observe();
  const until = async (check) => {
    const deadline = Date.now() + 15000;
    while (!await check()) { if (Date.now() > deadline) throw new Error('Browser condition timed out'); await sleep(20); }
  };
  const open = async () => {
    await page.goto(server.url);
    await page.getByRole('button', { name: 'New run', exact: true }).click();
    await page.getByRole('button', { name: 'Browse', exact: true }).click();
  };
  const at = async path => until(async () => await page.locator('.repository-current').textContent().catch(() => '') === path);
  const go = async path => { await page.getByLabel('Folder on this computer', { exact: true }).fill(path); await page.getByLabel('Folder on this computer', { exact: true }).press('Enter'); };
  const storageKey = 'sociotechnic.repository-starting-folder';
  const saved = () => page.evaluate(key => localStorage.getItem(key), storageKey);
  await open(); await at(projects);
  assert.equal(await saved(), null);
  await go(projects); await at(projects); await until(async () => await saved() === projects);
  await page.getByRole('button', { name: 'existing', exact: true }).click(); await at(join(projects, 'existing'));
  assert.equal(await saved(), projects);
  await page.getByRole('button', { name: 'Parent folder', exact: true }).click(); await at(projects);
  await go(join(root, 'missing'));
  await page.getByRole('alert').filter({ hasText: 'existing, accessible directory' }).waitFor();
  assert.equal(await saved(), projects);
  await go(projects); await at(projects);
  await page.getByRole('button', { name: 'New folder', exact: true }).click();
  await page.getByLabel('New folder name', { exact: true }).fill('../escape');
  await page.getByLabel('New folder name', { exact: true }).press('Enter');
  await page.getByRole('alert').filter({ hasText: 'one folder name' }).waitFor();
  await until(() => page.getByLabel('New folder name', { exact: true }).evaluate(el => el === document.activeElement));
  await page.getByLabel('New folder name', { exact: true }).fill('existing');
  await page.getByLabel('New folder name', { exact: true }).press('Enter');
  await page.getByRole('alert').filter({ hasText: 'already exists' }).waitFor();
  await page.getByLabel('New folder name', { exact: true }).press('Escape');
  assert.equal(await page.getByRole('dialog', { name: 'Start a run' }).count(), 1);
  await page.getByRole('button', { name: 'New folder', exact: true }).click();
  await page.route('**/api/repositories/create', route => route.abort());
  await page.getByLabel('New folder name', { exact: true }).fill('new project');
  await page.getByRole('button', { name: 'Create folder', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Cannot reach Sociotechnic' }).waitFor();
  assert.equal(await page.getByLabel('New folder name', { exact: true }).inputValue(), 'new project');
  await page.unroute('**/api/repositories/create');
  let release, requested;
  const held = new Promise(resolve => { release = resolve; });
  const pending = new Promise(resolve => { requested = resolve; });
  await page.route('**/api/repositories/create', async route => { requested(); await held; await route.continue(); });
  await page.getByRole('button', { name: 'Create folder', exact: true }).click();
  await pending;
  assert.equal(await page.getByRole('button', { name: 'Create folder', exact: true }).isDisabled(), true);
  assert.equal(await page.getByRole('button', { name: 'Close new run', exact: true }).isDisabled(), true);
  assert.equal(await page.getByRole('button', { name: 'Go', exact: true }).isDisabled(), true);
  release();
  const target = join(projects, 'new project');
  await at(target); await page.unroute('**/api/repositories/create');
  assert.deepEqual(readdirSync(target), []);
  assert.equal(await saved(), projects);
  await page.getByRole('button', { name: 'Use this folder', exact: true }).click();
  assert.equal(await page.getByLabel('Repository path', { exact: true }).inputValue(), target);
  await page.getByLabel('Initialize Git if needed', { exact: true }).uncheck();
  const runType = page.getByLabel('Run type', { exact: true });
  assert.deepEqual(await runType.locator('option').allTextContents(), ['Feature or fix', 'New repository', 'Design ceremony', 'Comment cleanup']);
  await runType.selectOption('repository');
  const init = page.getByRole('checkbox', { name: 'Initialize Git (required for a new repository)', exact: true });
  assert.equal(await init.isChecked(), true); assert.equal(await init.isDisabled(), true);
  await page.getByText('For a UI without an existing scaffold, we suggest our house special:', { exact: false }).waitFor();
  await page.getByLabel('What do you want to build?', { exact: true }).fill('Add a utility function');
  await page.screenshot({ path: join(output, 'run-wizard-new-repository.png') });
  await page.getByRole('button', { name: 'Start planning', exact: true }).click();
  await page.getByRole('button', { name: 'Continue build', exact: true }).waitFor({ timeout: 20000 });
  const git = (...args) => execFileSync('git', args, { cwd: target, encoding: 'utf8' }).trim();
  assert.equal(git('rev-list', '--count', 'HEAD'), '1');
  assert.deepEqual(git('ls-tree', '--name-only', 'HEAD').split('\n'), ['.gitignore', 'readme.md']);
  const id = new URLSearchParams(new URL(page.url()).hash.slice(1)).get('job');
  assert.equal(await readJob(id, job => job.status), 'planned');
  const state = await context.storageState();
  await context.close();
  context = await browser.newContext({ storageState: state, viewport: { width: 390, height: 844 }, colorScheme: 'dark', reducedMotion: 'reduce' });
  page = await context.newPage(); observe();
  await open(); await at(projects);
  await page.getByRole('button', { name: 'New folder', exact: true }).click();
  await page.getByLabel('New folder name', { exact: true }).fill('another-project');
  const dimensions = await page.getByRole('dialog', { name: 'Start a run' }).evaluate(el => ({ width: el.clientWidth, scroll: el.scrollWidth }));
  assert.ok(dimensions.scroll <= dimensions.width + 1, JSON.stringify(dimensions));
  await page.getByRole('button', { name: 'Create folder', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: join(output, 'run-wizard-narrow.png') });
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.screenshot({ path: join(output, 'run-wizard-folders.png') });
  await go(home); await at(home); await until(async () => await saved() === home);
  await page.reload(); await page.getByRole('button', { name: 'New run', exact: true }).click(); await page.getByRole('button', { name: 'Browse', exact: true }).click(); await at(home);
  await page.evaluate(({ key, path }) => localStorage.setItem(key, path), { key: storageKey, path: join(root, 'deleted') });
  await page.reload(); await page.getByRole('button', { name: 'New run', exact: true }).click(); await page.getByRole('button', { name: 'Browse', exact: true }).click(); await at(home);
  assert.equal(await saved(), join(root, 'deleted'));
  await page.getByRole('button', { name: 'Cancel browsing', exact: true }).click();
  await until(() => page.getByRole('button', { name: 'Browse', exact: true }).evaluate(el => el === document.activeElement));
  await page.getByRole('button', { name: 'Close new run', exact: true }).click();
  await page.getByRole('button', { name: 'Agent library', exact: true }).click();
  await page.getByRole('heading', { name: 'Agent library', exact: true }).waitFor();
  await page.addInitScript(() => {
    Storage.prototype.getItem = () => { throw new Error('Storage disabled'); };
    Storage.prototype.setItem = () => { throw new Error('Storage disabled'); };
  });
  await open(); await at(projects);
  await page.getByRole('status').filter({ hasText: 'Browser storage is unavailable' }).waitFor();
  await go(home); await at(home);
  await page.getByRole('status').filter({ hasText: 'will not be remembered' }).waitFor();
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ ok: true, output, verified: ['default and saved start points', 'browser session persistence and modification', 'invalid path fallback and recovery', 'storage failure recovery', 'directory navigation without preference changes', 'creation validation, offline retry and duplicate prevention', 'Git tracking and initial commit', 'feature plan hold', 'run type options and selection', 'keyboard focus and Escape', 'narrow layout', 'sibling agent library'] }));
} finally {
  await browser?.close();
  await server?.close();
  await store.close(); setStore(undefined);
  rmSync(root, { recursive: true, force: true });
}
