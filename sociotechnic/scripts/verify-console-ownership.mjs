import assert from 'node:assert/strict';
import { execFile, execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { hostname, tmpdir } from 'node:os';
import { join } from 'node:path';
import { setTimeout as sleep } from 'node:timers/promises';
import { promisify } from 'node:util';
import { createMemoryStore, setStore } from '../src/db/store.ts';
import { initializeAgentVersions } from '../src/agent-versions.ts';
import { createJobOperation } from '../src/job-store.ts';
import { newJob } from '../src/engine.ts';
import { owningConsoleUrl } from '../src/driver-location.ts';
import { fakeRunner } from '../ui/runner.ts';
import { startServer } from '../ui/server.ts';

const root = mkdtempSync(join(tmpdir(), 'sociotechnic-ownership-browser-'));
const proof = process.env.SOCIOTECHNIC_BROWSER_PROOF ?? mkdtempSync(join(tmpdir(), 'sociotechnic-ownership-proof-'));
mkdirSync(proof, { recursive: true });
console.log(`Browser proof: ${proof}`);
process.env.SOCIOTECHNIC_HOME = root;
process.env.SOCIOTECHNIC_DATABASE_URL = 'off';
const store = createMemoryStore();
setStore(store);
const session = `console-ownership-${process.pid}`;
const execute = promisify(execFile);
const browser = async (...args) => (await execute('agent-browser', ['--session', session, ...args], { timeout: 30_000 })).stdout.trim();
let owner, observer, release = () => {};
try {
  await initializeAgentVersions(store, [], []);
  const repo = join(root, 'repo'); mkdirSync(repo);
  const git = (...args) => execFileSync('git', ['-c', 'user.name=Browser fixture', '-c', 'user.email=test@example.invalid', '-c', 'commit.gpgsign=false', '-c', 'core.hooksPath=/dev/null', ...args], { cwd: repo, stdio: 'ignore' });
  git('init', '-q', '-b', 'main'); writeFileSync(join(repo, 'README.md'), 'ownership browser fixture\n'); git('add', '.'); git('commit', '-qm', 'fixture');
  const { job: id } = await createJobOperation(() => newJob(repo, 'Keep the owning console visible', null));
  const gate = new Promise(resolve => { release = resolve; });
  const delegate = fakeRunner(new URL('../tests/fixtures/fake-agent.mjs', import.meta.url).pathname);
  owner = await startServer({ port: 0, runner: () => ({ name: delegate.name, run: async (...args) => { await gate; return delegate.run(...args); } }) });
  observer = await startServer({ port: 0 });
  await owner.drivers.run(id, 'run', ['planned']);
  const destination = owningConsoleUrl(owner.url, id);
  const observingUrl = owningConsoleUrl(observer.url, id);
  await browser('set', 'viewport', '1440', '1000');
  await browser('open', observingUrl);
  await browser('wait', '--text', 'Running in another console');
  assert.equal(await browser('get', 'attr', '.human-actions a', 'href'), destination);
  const controls = await browser('get', 'text', '.human-actions');
  assert.match(controls, /Open owning console/);
  assert.doesNotMatch(controls, /Continue run|Recover worktree|Pause|Stop run/);
  const contrast = await browser('eval', '(() => { const s = getComputedStyle(document.querySelector(".human-actions a")); const luminance = color => { const rgb = color.match(/[\\d.]+/g).slice(0, 3).map(Number).map(v => { v /= 255; return v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; }); return rgb[0] * 0.2126 + rgb[1] * 0.7152 + rgb[2] * 0.0722; }; const a = luminance(s.color), b = luminance(s.backgroundColor); return (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05); })()');
  assert.ok(Number(contrast) >= 4.5, `Owning-console link contrast: ${contrast}`);
  await browser('screenshot', join(proof, 'external-desktop.png'), '--full');
  await browser('set', 'viewport', '390', '844');
  await sleep(250);
  assert.equal(await browser('eval', 'document.documentElement.scrollWidth <= window.innerWidth'), 'true');
  assert.ok(Number(await browser('eval', 'document.querySelector(".human-actions a").getBoundingClientRect().height')) >= 40);
  await browser('screenshot', join(proof, 'external-mobile.png'), '--full');
  await browser('eval', 'document.querySelector(".human-actions a").focus()');
  assert.equal(await browser('eval', 'document.activeElement.textContent.includes("Open owning console")'), 'true');
  await browser('press', 'Enter');
  await browser('wait', '--text', 'Agents are working');
  assert.equal(await browser('get', 'url'), destination);
  assert.match(await browser('get', 'text', '.human-actions'), /Pause/);

  await browser('open', observingUrl);
  await browser('wait', '--text', 'Running in another console');
  owner.drivers.pause(id); release();
  await owner.drivers.settled(id);
  const continueLabel = (await store.storedJob(id)).status === 'planned' ? 'Continue build' : 'Continue run';
  await browser('wait', '--text', continueLabel);
  assert.doesNotMatch(await browser('get', 'text', '.human-actions'), /Open owning console/);

  await store.setDriver(id, { host: hostname(), pid: process.pid, owner: 'ui', consoleUrl: 'javascript:alert(1)' });
  await browser('wait', '--text', 'Running in another console');
  assert.equal(await browser('get', 'count', '.human-actions a'), '0');
  assert.match(await browser('get', 'text', '.human-actions'), /Refresh status/);
  await store.setDriver(id, { host: hostname(), pid: 2147483647, owner: 'ui', consoleUrl: owner.url });
  await browser('wait', '--text', 'The previous driver process has stopped');
  assert.ok((await browser('get', 'text', '.human-actions')).includes(continueLabel));
  await store.setDriver(id, null);
  await sleep(150);
  console.log(JSON.stringify({ passed: true, proof, checks: ['two-server ownership', 'safe exact-job link', 'no local resume/pause/stop', 'desktop and mobile', 'keyboard navigation', 'automatic ownership release refresh', 'unknown location', 'interrupted owner'] }, null, 2));
} finally {
  release();
  await browser('close').catch(() => {});
  await observer?.close(); await owner?.close(); await store.close(); setStore(undefined);
  rmSync(root, { recursive: true, force: true });
}
