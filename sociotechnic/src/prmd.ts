import type { ChecksReport } from "./checks.ts";
import type { Job } from "./job.ts";
import type { Plan } from "./plan.ts";
import type { RoleUsage } from "./usage.ts";
import { parsePlanSteps, sectionLines } from "./verdict.ts";

export const PR_FOOTER = "🤖 Generated with [Claude Code](https://claude.com/claude-code)";

export type PrInput = {
  job: Job;
  plan: Plan;
  conformanceText: string | null;
  buildText: string | null;
  checks: ChecksReport | null;
  prNotes: string | null;
  usage: readonly RoleUsage[];
  sha: string;
};

function cell(text: string): string {
  return text.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
}

function stageStatus(stageId: string, stageTitle: string, rows: ReturnType<typeof parsePlanSteps>): string | null {
  if (rows === null) return null;
  const row = rows.find((r) => {
    const s = r.stage.replace(/`/g, "").trim();
    return s === stageId || s.startsWith(`${stageId} `) || s.startsWith(`${stageId}:`) || s === stageTitle;
  });
  return row === undefined ? null : row.status;
}

export function acceptanceBullets(buildText: string | null): string[] {
  if (buildText === null) return [];
  return (sectionLines(buildText, "Acceptance") ?? []).filter((l) => /^\s*[-*]\s/.test(l)).map((l) => l.trimEnd());
}

export function renderPr(i: PrInput): string {
  const out: string[] = [`# ${i.plan.title}`, "", "## Summary", "", i.plan.summary, "", "## Plan", ""];
  const rows = i.conformanceText === null ? null : parsePlanSteps(i.conformanceText);
  const tableUsable = rows !== null && rows.length > 0;
  for (const s of i.plan.stages) {
    const status = tableUsable ? stageStatus(s.id, s.title, rows) : null;
    out.push(`- ${s.id} — ${s.title}${status === null ? "" : ` (${status})`}`);
  }
  if (tableUsable) {
    for (const r of rows.filter((x) => x.status === "added")) out.push(`- ${r.stage} (added) — ${r.justification}`);
  }

  out.push("", "## Acceptance", "");
  const bullets = acceptanceBullets(i.buildText);
  out.push(...(bullets.length > 0 ? bullets : ["- (no acceptance bullets in the latest build.md)"]));

  out.push("", "## Checks", "");
  if (i.checks === null || i.checks.results.length === 0) {
    out.push(i.checks === null ? "No checks.json recorded." : "No checks configured.");
  } else {
    out.push("| check | command | result | exit | duration |", "| --- | --- | --- | --- | --- |");
    for (const r of i.checks.results) {
      const result = r.pass ? "pass" : r.timedOut ? "timeout" : "fail";
      out.push(`| ${cell(r.name)} | \`${cell(r.run)}\` | ${result} | ${String(r.exitCode)} | ${(r.durationMs / 1000).toFixed(1)}s |`);
    }
  }

  out.push("", "## Reviews", "", "| round | lens | verdict | blocking findings |", "| --- | --- | --- | --- |");
  for (const round of i.job.rounds) {
    for (const [lens, parsed] of Object.entries(round.reviews)) {
      out.push(`| ${round.n} | ${lens} | ${parsed.effective} | ${parsed.blocking} |`);
    }
  }

  if (i.prNotes !== null && i.prNotes.trim() !== "") out.push("", "## Reviewer notes", "", i.prNotes.trimEnd());

  out.push("", "## Usage", "", "| role | model | effort | dispatches | usage |", "| --- | --- | --- | --- | --- |");
  for (const u of i.usage) {
    const usage = Object.keys(u.usage).length === 0 ? "-" : `\`${cell(JSON.stringify(u.usage))}\``;
    out.push(`| ${u.role} | ${u.model} | ${u.effort} | ${u.dispatches} | ${usage} |`);
  }

  out.push("", "---", "", `Generated by sociotechnic job ${i.job.id} at ${i.sha}`, "", PR_FOOTER, "");
  return out.join("\n");
}
